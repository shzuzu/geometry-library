def area(a, h):
    """
    Вычисляет площадь треугольника по стороне и проведенной к ней высоте.

    Параметры:
        a (float | int): Длина стороны треугольника.
        h (float | int): Высота, опущенная на сторону a.

    Возвращаемое значение:
        float: Площадь треугольника.

    Пример вызова:
        >>> area(6, 4)
        12.0
    """
    return (a * h) / 2


def perimeter(a, b, c):
    """
    Вычисляет периметр треугольника по длинам трех сторон.

    Параметры:
        a (float | int): Первая сторона.
        b (float | int): Вторая сторона.
        c (float | int): Третья сторона.

    Возвращаемое значение:
        float | int: Периметр треугольника.

    Пример вызова:
        >>> perimeter(3, 4, 5)
        12
    """
    return a + b + c
